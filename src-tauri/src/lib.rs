/// Handles to the tray menu items, so their labels can be translated at runtime
pub struct TrayMenuItems {
    pub show: MenuItem<Wry>,
    pub quit: MenuItem<Wry>,
}

// Build the Tauri context
fn generate_context() -> tauri::Context<Wry> {
    tauri::generate_context!()
}

/// Entry point of the Tauri application
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    // Set up tauri_specta for type safe communication between frontend and backend
    let builder = tauri_specta::Builder::<Wry>::new()
        // Register every command the frontend is allowed to call
        .commands(tauri_specta::collect_commands![
            greet,
            get_config,
            save_config,
            search,
            get_page,
            get_comic,
            create_download_task,
            pause_download_task,
            resume_download_task,
            cancel_download_task,
            get_downloaded_comics,
            export_pdf,
            export_cbz,
            get_search_suggestions,
            get_logs_dir_size,
            show_path_in_file_manager,
            update_tray_menu_labels,
            get_cover_data,
            get_synced_comic,
            get_image_data,
            download_comics_by_ids,
        ])
        // Register every event the frontend can listen to
        .events(tauri_specta::collect_events![
            LogEvent,
            DownloadTaskEvent,
            DownloadSpeedEvent,
            ExportPdfEvent,
            ExportCbzEvent,
        ]);

    // Export the TypeScript bindings automatically in debug builds
    #[cfg(debug_assertions)]
    builder
        .export(
            specta_typescript::Typescript::default()
                // Map Rust's BigInt to TypeScript's Number
                .bigint(specta_typescript::BigIntExportBehavior::Number)
                // Format the generated code with prettier
                .formatter(specta_typescript::formatter::prettier)
                .header("// @ts-nocheck"), // disable typescript checks
            "../src/bindings.ts",
        )
        .expect("Failed to export typescript bindings");

    // Build and run the Tauri application
    tauri::Builder::default()
        // The dialog plugin provides the native file and directory pickers
        .plugin(tauri_plugin_dialog::init())
        // The opener plugin opens links and files in the system default application
        .plugin(tauri_plugin_opener::init())
        // Mount the command handler generated by specta
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            // Keep the global app handle around for later use
            utils::APP_HANDLE.get_or_init(|| app.handle().clone());

            // Mount the events so the backend can send typed events to the frontend
            builder.mount_events(app);

            // Get the data directory of the application
            let app_data_dir = app
                .path()
                .app_data_dir()
                .context("get app_data_dir failed")?;

            // Make sure the application data directory exists
            std::fs::create_dir_all(&app_data_dir).context(format!(
                "create app_data_dir `{}` failed",
                app_data_dir.display()
            ))?;

            // Load the configuration and hand it to Tauri's state management
            let config = RwLock::new(Config::new(app.handle())?);
            app.manage(config);

            // Create the Hitomi client and hand it to Tauri's state management
            let hitomi_client = HitomiClient::new(app.handle().clone());
            app.manage(hitomi_client);

            // Create the download manager and hand it to Tauri's state management
            let download_manager = DownloadManager::new(app.handle());
            app.manage(download_manager);

            // Set up logging
            logger::init(app.handle())?;

            // Build the system tray menu
            //
            // The tray is the only part of the interface the backend renders itself, so it
            // cannot read the frontend locale files. It starts out English and the frontend
            // pushes the translated labels through `update_tray_menu_labels` on startup and
            // whenever the language changes, which keeps the locale files the single source.
            let show_item = MenuItem::with_id(app, "show", "Show Window", true, None::<&str>)?;
            let quit_item = MenuItem::with_id(app, "quit", "Quit", true, None::<&str>)?;
            let menu = Menu::with_items(app, &[&show_item, &quit_item])?;
            app.manage(TrayMenuItems {
                show: show_item.clone(),
                quit: quit_item.clone(),
            });

            // Build the system tray icon
            let _tray = TrayIconBuilder::new()
                .icon(app.default_window_icon().unwrap().clone())
                .menu(&menu)
                .tooltip("hitomi-downloader")
                .on_menu_event(move |app, event| match event.id().as_ref() {
                    "show" => {
                        if let Some(window) = app.get_webview_window("main") {
                            let _ = window.show();
                            let _ = window.set_focus();
                        }
                    }
                    "quit" => {
                        app.exit(0);
                    }
                    _ => {}
                })
                .on_tray_icon_event(|tray, event| {
                    if let TrayIconEvent::Click {
                        button: MouseButton::Left,
                        button_state: MouseButtonState::Up,
                        ..
                    } = event
                    {
                        let app = tray.app_handle();
                        if let Some(window) = app.get_webview_window("main") {
                            let _ = window.show();
                            let _ = window.set_focus();
                        }
                    }
                })
                .build(app)?;

            Ok(())
        })
        .on_window_event(|window, event| {
            // Intercept the close event and hide the window to the tray instead
            if let tauri::WindowEvent::CloseRequested { api, .. } = event {
                // Prevent the window from closing
                api.prevent_close();
                // Hide the window
                let _ = window.hide();
            }
        })
        .run(generate_context())
        .expect("error while running tauri application");
}
